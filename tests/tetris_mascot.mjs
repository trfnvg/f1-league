import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import vm from 'node:vm';
const scope = {window: {}};
vm.runInNewContext(await fs.readFile(new URL('../league/static/league/tetris-mascot.js', import.meta.url), 'utf8'), scope);
let restarts=0;
const element = {dataset: {}, getAnimations: () => [{cancel(){restarts++;},play(){}}]};
const mascot = new scope.window.PitStackMascot(element);
const game = {phase: 'running', clearSerial: 0, lastClear: 0, lockSerial: 0, clearing: [], paused: false};
assert.equal(element.dataset.state, 'idle');
const before = JSON.stringify(game);
for (let i=0;i<1000;i++) { mascot.observe(game); mascot.step(16, false); }
assert.equal(JSON.stringify(game), before, 'Decoration cannot change gameplay');
game.clearSerial++; game.lastClear=1; mascot.observe(game);
assert.equal(element.dataset.state, 'placing');
for (let i=0;i<16;i++) mascot.step(50, false);
assert.equal(element.dataset.state, 'idle');
game.phase='clearing'; game.clearing=[16,17,18,19];game.lockSerial++;
mascot.observe(game);
assert.equal(element.dataset.state,'anticipate','Four-row charge is noticed before the explosion');
for(let i=0;i<8;i++){mascot.observe(game);mascot.step(50,false);}
assert.equal(element.dataset.state,'anticipate','Anticipation holds until the actual clear');
game.phase='running';game.clearing=[];game.clearSerial++; game.lastClear=4; mascot.observe(game);
assert.equal(element.dataset.state, 'celebrate');
assert.equal(restarts,1);
mascot.step(50, false);
const remaining=mascot.remaining;
game.paused=true; mascot.observe(game);
for(let i=0;i<100;i++) mascot.step(50, true);
assert.equal(mascot.remaining, remaining, 'Pause freezes finite reaction');
assert.equal(element.dataset.paused, 'true');
game.paused=false; mascot.observe(game);
for(let i=0;i<60;i++) { mascot.observe(game); mascot.step(50, false); }
assert.equal(element.dataset.state, 'idle', 'Same clear cannot retrigger a reaction');
assert.equal(restarts,1,'Same clear never restarts CSS effects');
game.clearSerial++;game.lastClear=4;mascot.observe(game);
game.clearSerial++;mascot.observe(game);
assert.equal(restarts,3,'A consecutive four-line clear restarts one reaction');
assert.equal(mascot.remaining,3000,'Consecutive clears replace, not queue effects');
game.clearSerial++;game.lastClear=1;mascot.observe(game);
assert.equal(element.dataset.state,'celebrate','Small clear does not interrupt a big celebration');
game.phase='over'; mascot.observe(game);
assert.equal(element.dataset.state, 'over');
assert.equal(mascot.remaining, 0);
mascot.reset();
assert.equal(element.dataset.state, 'idle');
assert.equal(element.dataset.paused, 'false');
game.phase='ready';game.clearSerial=0;mascot.observe(game);
assert.equal(mascot.serial,0);
game.phase='running';game.lockSerial++;mascot.observe(game);
assert.equal(element.dataset.state,'placing','Ordinary landings receive a short nod');
const missing = new scope.window.PitStackMascot(null);
missing.observe(game);missing.step(50,false);
console.log('Pit Stack mascot passed: read-only observer, landings, anticipation, four-line explosion, pause, expiry, no retrigger, bounded consecutive clears, game-over, restart, absent element.');
